class User:

    def __init__(self,
                 id,
                 full_name,
                 username,
                 email,
                 mobile,
                 password,
                 device_id):

        self.id = id
        self.full_name = full_name
        self.username = username
        self.email = email
        self.mobile = mobile
        self.password = password
        self.device_id = device_id